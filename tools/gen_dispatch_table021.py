#!/usr/bin/env python3
"""Generate runtime021/dispatch_table.inc: the generated-function cases of
the runtime008/010/011/021 dispatch.inc files as one sorted table
{address, function}, used by the play build's per-call-site inline cache
(REX_CALL_INDIRECT_FUNC under CC_FAST). Cases that are not a plain
"case 0x...: sub_X(ctx,base); return;" (kernel services, xstart) are left
to the switch in dispatch_impl.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ["runtime008/dispatch.inc", "runtime010/dispatch.inc",
           "runtime011/dispatch.inc", "runtime021/dispatch.inc"]
pat = re.compile(r"^case (0x[0-9A-Fa-f]+): ((?:sub_|__)[A-Za-z0-9_]+)\(ctx,base\); return;$")
entries = {}
for src in SOURCES:
    for line in (ROOT / src).read_text().splitlines():
        m = pat.match(line.strip())
        if not m:
            continue
        addr = int(m.group(1), 16)
        if addr in entries and entries[addr] != m.group(2):
            raise SystemExit(f"{src}: {m.group(1)} already maps to {entries[addr]}")
        entries[addr] = m.group(2)
out = ROOT / "runtime021/dispatch_table.inc"
lines = ["// Generated by tools/gen_dispatch_table021.py from the dispatch.inc files.",
         "// Sorted by guest address. Do not edit.",
         f"static const CcDispatchEntry cc_dispatch_table[{len(entries)}] = {{"]
for addr in sorted(entries):
    lines.append(f"  {{0x{addr:08X}u, {entries[addr]}}},")
lines.append("};")
out.write_text("\n".join(lines) + "\n", newline="\n")
print(f"{out}: {len(entries)} entries")
