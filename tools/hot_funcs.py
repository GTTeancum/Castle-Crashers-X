"""Hot-code list for the Xbox build from console profiles.

usage: hot_funcs.py <main.map> <main.exe> <out .inc> <samples>...

Counts self samples per function (as tools/xbox_symbolize.py) over all the
given sample files and writes runtime021/hot_funcs.inc: a CC_HOT_<name>
probe for every generated function (sub_XXXXXXXX, with or without _exact)
seen in at least 0.02% of the samples. bridge.cpp places those functions in
the .text$hot section so the code the game spends its time in is contiguous
(the console's code pages / instruction TLB cover far less than the 11 MB
of generated code).
"""
import re
import sys
from collections import Counter

sys.path.insert(0, __file__.rsplit("\\", 1)[0].rsplit("/", 1)[0])
import xbox_symbolize as xs  # noqa: E402


def main(argv):
    mapf, exe, out = argv[:3]
    addrs, names = xs.load_map(mapf)
    import bisect
    counts = Counter()
    total = 0
    for path in argv[3:]:
        for line in open(path):
            p = line.split()
            if len(p) < 64:
                continue
            ws = [int(w, 16) for w in p[3:]]
            k = next((i for i in range(len(ws) - 2) if ws[i + 1] == 8 and (ws[i + 2] & 0xFFFF0002) == 2), None)
            if k is None or ws[k] >= 0x80000000:
                continue
            i = bisect.bisect_right(addrs, ws[k]) - 1
            if i < 0:
                continue
            counts[xs.demangle(names[i])] += 1
            total += 1
    hot = sorted(n for n, c in counts.items()
                 if c * 5000 >= total and re.fullmatch(r"sub_[0-9A-F]{8}(_exact)?", n))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/hot_funcs.py from console profiles: generated\n")
        f.write("// functions placed in .text$hot (see DEFINE_REX_FUNC in bridge.cpp).\n")
        for n in hot:
            f.write("#define CC_HOT_%s ~, 1\n" % n)
    print("samples %d hot generated functions %d" % (total, len(hot)))


if __name__ == "__main__":
    main(sys.argv[1:])
